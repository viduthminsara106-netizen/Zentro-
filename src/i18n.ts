export function translateByLanguage(
  rawLang: string | undefined | null,
  enText: string,
  siText?: string
): string {
  const lang = normalizeLangCode(rawLang);
  if (lang === 'English') {
    return enText;
  }
  if (lang === 'Sinhala') {
    if (siText && siText.trim().length > 0) {
      return siText;
    }
    if (EN_TO_SI_EXACT[enText]) {
      return EN_TO_SI_EXACT[enText];
    }
    return enText;
  }

  const pairs = MULTI_LANG_TERMS[lang];
  if (!pairs) return enText;

  // Check exact match first
  for (const [enKey, targetVal] of pairs) {
    if (enText === enKey) {
      return targetVal;
    }
  }

  // Otherwise replace longer phrases first
  let output = enText;
  const sortedPairs = [...pairs].sort((a, b) => b[0].length - a[0].length);
  for (const [enKey, targetVal] of sortedPairs) {
    if (enKey.length >= 4 && output.includes(enKey)) {
      output = output.split(enKey).join(targetVal);
    }
  }
  return output;
}
