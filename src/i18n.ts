// Comprehensive Multi-Language Translation Engine for Zentro
// Supports: English, Sinhala, Tamil, Hindi, Arabic, German, French, Japanese, Malay, Portuguese

export type SupportedLangCode =
  | 'English'
  | 'Sinhala'
  | 'Tamil'
  | 'Hindi'
  | 'Arabic'
  | 'German'
  | 'French'
  | 'Japanese'
  | 'Malay'
  | 'Portuguese';

export function normalizeLangCode(raw?: string | null): SupportedLangCode {
  if (!raw) return 'English';
  const s = raw.trim().toLowerCase();
  if (s.includes('sinhala') || s.includes('සිංහල') || s === 'si') return 'Sinhala';
  if (s.includes('tamil') || s.includes('தமிழ்') || s === 'ta') return 'Tamil';
  if (s.includes('hindi') || s.includes('हिन्दी') || s === 'hi') return 'Hindi';
  if (s.includes('arabic') || s.includes('العربية') || s === 'ar') return 'Arabic';
  if (s.includes('german') || s.includes('deutsch') || s === 'de') return 'German';
  if (s.includes('french') || s.includes('français') || s.includes('francais') || s === 'fr')
    return 'French';
  if (s.includes('japanese') || s.includes('日本語') || s === 'ja') return 'Japanese';
  if (s.includes('malay') || s.includes('melayu') || s === 'ms') return 'Malay';
  if (s.includes('portuguese') || s.includes('português') || s === 'pt') return 'Portuguese';
  return 'English';
}

